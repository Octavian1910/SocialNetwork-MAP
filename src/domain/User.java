package domain;

import java.util.Objects;

/**
 * Domain entity representing an individual registered in the social network.
 */
public class User implements Entity<Long> {
    private Long id;
    private final String firstName;
    private final String lastName;

    /**
     * Constructs a User when the ID is already known (e.g., loaded from database).
     *
     * @param id        the unique identifier
     * @param firstName the user's first name
     * @param lastName  the user's last name
     */
    public User(Long id, String firstName, String lastName) {
        this.id = id;
        this.firstName = firstName;
        this.lastName = lastName;
    }

    /**
     * Constructs a User before persistence (ID will be generated by the database).
     *
     * @param firstName the user's first name
     * @param lastName  the user's last name
     */
    public User(String firstName, String lastName) {
        this(null, firstName, lastName);
    }

    @Override
    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getFirstName() {
        return firstName;
    }

    public String getLastName() {
        return lastName;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || getClass() != o.getClass()) return false;
        User user = (User) o;
        return Objects.equals(id, user.id);
    }

    @Override
    public int hashCode() {
        return Objects.hash(id);
    }

    @Override
    public String toString() {
        return "User{id=" + id + ", firstName='" + firstName + "', lastName='" + lastName + "'}";
    }
}